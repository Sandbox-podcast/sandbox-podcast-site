export type HistoryArtworkSubject = keyof typeof HISTORY_ARTWORK_GROUPS;

const subjectsByEvent = new Map<string, HistoryArtworkSubject>(
  Object.entries(HISTORY_ARTWORK_GROUPS).flatMap(([subject, ids]) =>
    ids.map((id) => [id, subject as HistoryArtworkSubject] as const),
  ),
);

const fallbackSubjects: Record<HistoryCategory, HistoryArtworkSubject> = {
  model: 'model',
  research: 'neural',
  product: 'agent',
  milestone: 'compute',
  governance: 'governance',
};

export function historyArtworkSubject(event: HistoryEvent): HistoryArtworkSubject {
  return subjectsByEvent.get(event.id) ?? fallbackSubjects[event.category];
}

export function historyArtworkPath(event: HistoryEvent): string {
  return `/images/time-machine/events/${event.id}.svg`;
}
